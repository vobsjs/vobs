import { existsSync } from 'node:fs'
import { resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { analyzeSource, compileWithSourceMap } from '@vobs/compiler'
import { DIAGNOSTIC_GUIDES, findDiagnosticGuide } from '@vobs/runtime'
import { checkContractSync } from './agent-doc.js'
import { cliVersion } from '../version.js'

/**
 * `vobs mcp` —— Model Context Protocol 的 **stdio** server（零依赖，手写 JSON-RPC 2.0）。
 *
 * ## 为什么做它
 *
 * 运行时反馈闭环不能是「人触发」的：Agent 需要标准协议入口自主调用
 * `check:runtime`。MCP 是行业事实标准（Next.js 的 next-devtools-mcp、
 * neo.mjs 的 neural-link 都把运行时状态暴露成 Agent 可自主调用的 tools）。
 * 这里暴露三个 tools，全部基于**已存在的纯函数/脚本**，不引入新能力只换协议：
 *
 * - `check_runtime` — 跑运行时护栏，返回机器可读 verdict（check-runtime.mjs --json）
 * - `explain_diagnostic` — 单个诊断码的 why / correct / wrong / rewrites（可直接机械替换）
 * - `contract_status` — 项目 AGENTS.md 契约与安装的框架版本是否漂移
 *
 * ## 诚实定位
 *
 * `check_runtime` 依赖 `scripts/check-runtime.mjs`（monorepo 内部脚本，起 dev server +
 * 真实 Chrome）。npm 下游项目还没有等价 CLI 入口（那是独立工作），此 tool 会返回
 * 明确的不可用说明；`explain_diagnostic` / `contract_status` 是纯函数，随处可用。
 *
 * ## 协议
 *
 * newline-delimited JSON-RPC 2.0 over stdio（MCP stdio transport）。只实现
 * `initialize` / `notifications/initialized` / `tools/list` / `tools/call` ——
 * MCP 的最小可用子集。schema 承诺 additive-only（与 explain --json 同一约定）。
 */

const PROTOCOL_VERSION = '2024-11-05'
const SERVER_INFO = { name: 'vobs-mcp', version: cliVersion }

const TOOLS = [
  {
    name: 'check_source_snippet',
    description: 'Static-check a vobs component snippet WITHOUT writing it to disk. Returns all VOBS_C* diagnostics (compile + analyze). Use this BEFORE writing generated code into the project — a pure in-memory pass, no Chrome, no dev server. Each diagnostic carries a verified before/after rewrite.',
    inputSchema: {
      type: 'object',
      properties: {
        code: { type: 'string', description: 'The full component source (JSX/TSX), including imports from @vobs/vobs' },
        filename: { type: 'string', description: 'Virtual filename for diagnostics (default snippet.tsx)' }
      },
      required: ['code']
    }
  },
  {
    name: 'check_runtime',
    description: 'Run the runtime guardrails in a real Chrome pass and return a machine-readable verdict. Requires scripts/check-runtime.mjs (monorepo). Slow: starts a dev server per run.',
    inputSchema: {
      type: 'object',
      properties: {
        routes: { type: 'string', description: 'Comma-separated routes to check (default: all routes from the router file)' },
        interact: { type: 'boolean', description: 'Also click every button and fill every input (slower, catches interaction-time failures)' }
      }
    }
  },
  {
    name: 'explain_diagnostic',
    description: 'Full metadata for one VOBS_C* code: severity, why, correct, wrong, and rewrites (verified before→after pairs; rewriting to `after` yields zero diagnostics).',
    inputSchema: {
      type: 'object',
      properties: {
        code: { type: 'string', description: 'e.g. VOBS_C233 or C233' }
      },
      required: ['code']
    }
  },
  {
    name: 'contract_status',
    description: 'Whether the project AGENTS.md contract (generated by `vobs agent-doc`) is in sync with the installed framework version. drifted → run `vobs agent-doc --write`.',
    inputSchema: { type: 'object', properties: {} }
  }
]

export interface McpState {
  readonly root: string
  initialized: boolean
}

export function createMcpState(root: string): McpState {
  return { root, initialized: false }
}

/**
 * 处理一条 MCP 消息，返回要写回 stdout 的 JSON-RPC 响应（通知类返回 null）。
 * 抽成纯函数：测试可以直接打消息进、断言消息出，不用走 stdio。
 */
export function handleMcpMessage(state: McpState, raw: unknown): object | null {
  const message = raw as { id?: unknown; method?: unknown; params?: { name?: unknown; arguments?: Record<string, unknown> } } | null
  if (!message || typeof message !== 'object' || typeof message.method !== 'string') return null
  const hasId = message.id !== undefined
  const respond = (result: object): object | null =>
    hasId ? { jsonrpc: '2.0', id: message.id, result } : null
  const fail = (code: number, text: string): object | null =>
    hasId ? { jsonrpc: '2.0', id: message.id, error: { code, message: text } } : null

  switch (message.method) {
    case 'initialize':
      state.initialized = true
      return respond({ protocolVersion: PROTOCOL_VERSION, capabilities: { tools: {} }, serverInfo: SERVER_INFO })

    case 'notifications/initialized':
      return null

    case 'tools/list':
      return respond({ tools: TOOLS })

    case 'tools/call': {
      const name = message.params?.name
      const toolArgs = message.params?.arguments ?? {}
      try {
        const content = runTool(state, String(name), toolArgs)
        return respond({ content: [{ type: 'text', text: content }] })
      } catch (error) {
        return respond({
          content: [{ type: 'text', text: error instanceof Error ? error.message : String(error) }],
          isError: true
        })
      }
    }

    default:
      return fail(-32601, `Unknown method: ${String(message.method)}`)
  }
}

function runTool(state: McpState, name: string, toolArgs: Record<string, unknown>): string {
  if (name === 'check_source_snippet') return runCheckSourceSnippet(toolArgs)
  if (name === 'check_runtime') return runCheckRuntime(state.root, toolArgs)
  if (name === 'explain_diagnostic') {
    const code = String(toolArgs.code ?? '').trim()
    if (!code) throw new Error('code is required')
    const normalized = code.toUpperCase().startsWith('VOBS_') ? code.toUpperCase() : `VOBS_${code.toUpperCase()}`
    const guide = findDiagnosticGuide(normalized)
    if (!guide) {
      const available = DIAGNOSTIC_GUIDES.map(item => item.code).join(', ')
      throw new Error(`No entry for ${normalized}. Known codes: ${available}`)
    }
    return JSON.stringify(guide, null, 2)
  }
  if (name === 'contract_status') {
    const sync = checkContractSync(state.root)
    return JSON.stringify({
      status: sync.status,
      ...(sync.status === 'drifted' ? { problems: sync.problems, action: 'run `vobs agent-doc --write`' } : {})
    }, null, 2)
  }
  throw new Error(`Unknown tool: ${name}. Available: ${TOOLS.map(tool => tool.name).join(', ')}`)
}

/**
 * 写前自检（MulFCoder 的 Judger 思路，2026-10-28）：Agent 在把生成代码写进项目**之前**，
 * 先对片段跑完整的静态通道（编译器诊断 + 分析器诊断）—— 纯内存、零副作用。
 * 返回的每条诊断带 code/message/fix（fix 指向 vobs explain，rewrites 经 explain --json 可得）。
 */
function runCheckSourceSnippet(toolArgs: Record<string, unknown>): string {
  const code = toolArgs.code
  if (typeof code !== 'string' || !code.trim()) throw new Error('code is required')
  const filename = typeof toolArgs.filename === 'string' && toolArgs.filename.trim()
    ? toolArgs.filename.trim()
    : 'snippet.tsx'
  const compiled = compileWithSourceMap(code, { filename }).diagnostics.map(item => ({
    code: item.code, severity: item.severity, message: item.message, fix: item.fix,
    line: item.location?.line ?? null, column: item.location?.column ?? null
  }))
  const analyzed = analyzeSource(code, filename).map(item => ({
    code: item.code, severity: item.severity, message: item.message, fix: item.fix,
    line: item.line, column: item.column
  }))
  const seen = new Set<string>()
  const diagnostics = [...compiled, ...analyzed].filter(item => {
    const key = `${item.code}|${item.line}|${item.column}`
    if (seen.has(key)) return false
    seen.add(key)
    return true
  }).map(item => ({
    ...item,
    // 内嵌改写指令（元数据第一条）—— AI 拿到诊断即拿到 before/after，不用二次调 explain
    rewrite: DIAGNOSTIC_GUIDES.find(guide => guide.code === item.code)?.rewrites?.[0] ?? null
  }))
  return JSON.stringify({
    filename,
    pass: diagnostics.length === 0,
    diagnostics,
    hint: diagnostics.length > 0
        ? 'Each diagnostic embeds a verified rewrite (before→after). Runtime behavior still needs `check_runtime` (Chrome pass).'
        : 'Snippet is clean by static channels. Runtime behavior still needs `check_runtime` (Chrome pass).'
  }, null, 2)
}

/** 跑运行时护栏（spawnSync —— MCP tools/call 的语义就是拿到完整结果再返回）。 */
function runCheckRuntime(root: string, toolArgs: Record<string, unknown>): string {
  const script = resolve(root, 'scripts', 'check-runtime.mjs')
  if (!existsSync(script)) {
    throw new Error(
      'check_runtime requires scripts/check-runtime.mjs (monorepo layout) — not found in this project. '
      + 'For downstream projects, run the runtime guardrails through your own harness instead; '
      + 'explain_diagnostic and contract_status work everywhere.'
    )
  }
  const argv = [script, '--json']
  if (typeof toolArgs.routes === 'string' && toolArgs.routes.trim()) argv.push('--routes', toolArgs.routes.trim())
  if (toolArgs.interact === true) argv.push('--interact')
  const result = spawnSync(process.execPath, argv, { cwd: root, encoding: 'utf8', timeout: 600_000 })
  if (result.error) throw new Error(`check_runtime failed to start: ${result.error.message}`)
  if (result.status !== 0 && !result.stdout.trim()) {
    throw new Error(`check_runtime failed (exit ${result.status ?? 'signal'}):\n${result.stderr.trim()}`)
  }
  return result.stdout.trim()
}

/** stdio 主循环：逐行读 JSON-RPC，逐条写响应。stdin 关闭（Agent 断开）时返回。 */
export async function mcpCommand(): Promise<void> {
  const state = createMcpState(resolve(process.cwd()))
  const readline = await import('node:readline')
  const rl = readline.createInterface({ input: process.stdin })
  const write = (message: object): void => {
    process.stdout.write(`${JSON.stringify(message)}\n`)
  }
  for await (const line of rl) {
    const trimmed = line.trim()
    if (!trimmed) continue
    let parsed: unknown
    try { parsed = JSON.parse(trimmed) } catch { continue }
    const response = handleMcpMessage(state, parsed)
    if (response !== null) write(response)
  }
}
