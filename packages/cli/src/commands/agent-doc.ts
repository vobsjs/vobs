import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { DIAGNOSTIC_GUIDES } from '@vobs/runtime'
import { AGENT_CONTRACT } from '../templates/agent-contract.js'

/**
 * `vobs agent-doc` — **generates** the framework contract into the current project
 * for any LLM / agent to read.
 *
 * ## Why "generate" instead of "hand-write"
 *
 * The contract evolves with the framework (new primitives, new diagnostics, revised fix
 * copy), so hand-written copies **inevitably drift apart**; whoever writes them may not
 * know the latest contract either. Generation is naturally version-bound:
 * `@vobs/cli@1.8.x` produces the 1.8.x contract.
 *
 * ## Design points
 *
 * 1. **Marker block**: only the content between `<!-- vobs:begin -->` and `<!-- vobs:end -->`
 *    is replaced; **the project's own conventions outside the block are preserved** —
 *    regenerating never clobbers your own content.
 * 2. **`--check`**: verifies that the copy in the project matches the current framework
 *    version; exits 1 on mismatch. CI-friendly — this turns "doc drift" from
 *    "someone has to remember" into "the machine blocks it".
 * 3. **`CLAUDE.md` contains only one line, `@AGENTS.md`**: the content lives in exactly
 *    one place, avoiding two drifting copies.
 * 4. Produced by the **framework**, never hand-copied by users; tool-agnostic
 *    (the content never mentions any specific LLM).
 */

const BEGIN = '<!-- vobs:begin generated by `vobs agent-doc --write`, do not hand-edit -->'
const END = '<!-- vobs:end -->'

export interface AgentDocOptions {
  /** Target directory; defaults to the current working directory. */
  readonly dir?: string
  /** Write files (otherwise print to stdout). */
  readonly write?: boolean
  /** Verify that the project's copy matches the current framework version; exit 1 on mismatch. */
  readonly check?: boolean
  /** Print only the contract body (without the marker block). */
  readonly body?: boolean
  /**
   * Lightweight agent knowledge-distribution channel (discoverable outside the project):
   * writes three publicly fetchable files into the given directory —
   * `llms.txt` (index, llms.txt convention), `vobs-context.md` (full contract),
   * `diagnostics.md` (why/correct/wrong for every diagnostic code).
   * The goal: agents that **have not installed vobs** can read the contract first, then decide to adopt it.
   */
  readonly llms?: string
}

/** The contract body is inlined in `templates/agent-contract.ts` (see the note there: file reads fail under full test runs). */
function readContract(): string {
  return AGENT_CONTRACT.trim()
}

/** Wrap the contract in the marker block — content outside the block belongs to the project and is never touched. */
function buildAgentsDoc(contract: string): string {
  return [
    BEGIN,
    '',
    contract,
    '',
    END,
    '',
    '<!-- Below are this project\'s own conventions; `vobs agent-doc --write` will not overwrite them. -->',
    '',
    '## Project conventions',
    '',
    '(Write your own directory structure, naming, business-flow rules here.)',
    ''
  ].join('\n')
}

/** Extract the marker-block content from a file (returns null when there is no block). */
function extractBlock(text: string): string | null {
  const start = text.indexOf(BEGIN)
  const end = text.indexOf(END)
  if (start < 0 || end < 0 || end < start) return null
  return text.slice(start, end + END.length)
}

export type ContractSyncStatus =
  | { readonly status: 'synced' }
  | { readonly status: 'missing' }
  | { readonly status: 'no-block' }
  | { readonly status: 'drifted'; readonly problems: readonly string[] }

/**
 * Contract version-sync check (shared by the `vobs check` main entry and `agent-doc --check`).
 *
 * "The contract ships with the framework version" must not remain a promise made only at
 * generation time — this turns it into a fact **verifiable on every check**: the contract
 * block already in the project (vobs:begin/end) is compared byte-for-byte against the current
 * framework contract; any mismatch is drift. `missing` / `no-block` are not drift —
 * agent-doc is an explicit opt-in capability, so projects without a generated contract
 * should not be nagged by the main entry (the CI hard-verification semantics of
 * `agent-doc --check` are kept separately inside agentDocCommand).
 */
export function checkContractSync(root: string): ContractSyncStatus {
  const agentsPath = resolve(root, 'AGENTS.md')
  if (!existsSync(agentsPath)) return { status: 'missing' }
  const existing = readFileSync(agentsPath, 'utf8')
  const block = extractBlock(existing)
  if (block === null) return { status: 'no-block' }
  const generated = buildAgentsDoc(readContract())
  if (block !== extractBlock(generated)) {
    return {
      status: 'drifted',
      problems: ['The vobs contract block in AGENTS.md is out of sync with the current framework version — diagnostic codes and semantic fixes added by the framework are missing from your existing contract']
    }
  }
  return { status: 'synced' }
}

/** Doc section for a single diagnostic code (shared by diagnostics.md and the single-code `diagnostics/<code>.md` pages). */
function renderGuideSection(guide: (typeof DIAGNOSTIC_GUIDES)[number]): string[] {
  const lines: string[] = [
    `## ${guide.code} · ${guide.severity} — ${guide.title}`,
    '',
    `why: ${guide.why}`,
    '',
    `correct: ${guide.correct}`,
    '',
    `wrong: ${guide.wrong}`,
    ''
  ]
  for (const rewrite of guide.rewrites ?? []) {
    lines.push(
      '```ts',
      `// before (triggers ${guide.code})`,
      rewrite.wrong,
      '// after (zero diagnostics)',
      rewrite.correct,
      '```',
      ''
    )
  }
  return lines
}

/** Diagnostics knowledge doc: why / correct / wrong / rewrites for every `VOBS_C*` (the fetchable form of `vobs explain`). */
export function buildDiagnosticsDoc(): string {
  const lines: string[] = [
    '# vobs diagnostics',
    '',
    'All `VOBS_C*` codes with why / correct / wrong, plus machine-applicable `rewrites`',
    '(before → after pairs verified by guide-verification: rewriting to `after` yields zero diagnostics).',
    'Runtime query: `vobs explain <code>` / `vobs explain --json`. Single-code pages: `diagnostics/<code>.md`.',
    ''
  ]
  for (const guide of DIAGNOSTIC_GUIDES) lines.push(...renderGuideSection(guide))
  return lines.join('\n')
}

/** Single-code page: fetch one diagnostic on demand instead of pulling the full table. */
export function buildSingleDiagnosticDoc(code: string): string | null {
  const guide = DIAGNOSTIC_GUIDES.find(item => item.code === code)
  if (!guide) return null
  return [
    `# ${guide.code} · ${guide.severity} — ${guide.title}`,
    '',
    ...renderGuideSection(guide).slice(1)
  ].join('\n')
}

/** llms.txt index (llms.txt convention: H1 + blockquote summary + link sections). */
export function buildLlmsIndex(): string {
  return [
    '# vobs',
    '',
    '> Signals-first compiled UI framework: run-once components, fine-grained updates, standard JSX.',
    '> AI-first: machine-generated contract, dual-layer diagnostics (static + runtime guardrails), every fix verified.',
    '',
    '## Start here',
    '',
    '- [vobs-context.md](/vobs-context.md): the full AI contract — component model (run-once), reactive graph semantics (conditional dependencies, on/untrack), JSX rules, error codes. Load this first.',
    '- [diagnostics.md](/diagnostics.md): every `VOBS_C*` code with why / correct / wrong.',
    '',
    '## CLI',
    '',
    '- `vobs agent-doc --write`: write this contract into your project AGENTS.md (marker-block merge, user content preserved).',
    '- `vobs check`: whole-repo static analysis + compiler diagnostics; also verifies the contract is in sync with the installed framework version.',
    '- `vobs explain <code>` / `vobs explain --json`: query any diagnostic (schema is stable, additive-only; includes verified `rewrites`).',
    '- `vobs check:runtime --json`: machine-readable runtime guardrail verdict `{ pass, routes: [{ route, status, guardFailures }] }` from a real Chrome pass — run it after generating code to self-verify before asking a human.',
    '- `vobs mcp`: MCP stdio server (JSON-RPC 2.0) exposing `check_runtime`, `explain_diagnostic`, `contract_status` — point a coding agent at it for autonomous verification.',
    '- Per-diagnostic pages: [diagnostics/VOBS_C233.md](/diagnostics/VOBS_C233.md) pattern (one file per code, fetch on demand instead of pulling the full table).'
  ].join('\n')
}

/** Context-cost metric (verifiable agent-friendliness: ArrowJS sells itself on "docs as a share of the context window"; same idea). */
export function estimateTokens(text: string): number {
  // Approximation: CJK chars ≈ 1 token each, ASCII ≈ 4 chars/token. The contract mixes
  // CJK and Latin scripts, so take the conservative upper bound.
  const cjk = (text.match(/[\u4e00-\u9fff\u3040-\u30ff]/gu) ?? []).length
  const rest = text.length - cjk
  return cjk + Math.ceil(rest / 4)
}

/**
 * Merge: keep everything outside the block, replace only the block.
 *
 * An existing hand-written `AGENTS.md` without a marker block is **never overwritten** —
 * the generated block is **appended after it**, preserving all of the user's original
 * content. Destroying someone's rules is worse than not generating at all.
 */
function mergeAgentsDoc(existing: string | null, generated: string): string {
  if (existing === null) return generated
  const block = extractBlock(generated)
  if (block === null) return generated
  if (extractBlock(existing) === null) return `${existing.trimEnd()}\n\n${block}\n`
  return existing.replace(extractBlock(existing)!, block)
}

export async function agentDocCommand(options: AgentDocOptions = {}): Promise<void> {
  const root = resolve(options.dir ?? process.cwd())
  const contract = readContract()

  if (options.body === true) {
    process.stdout.write(`${contract}\n`)
    return
  }

  const generated = buildAgentsDoc(contract)
  const agentsPath = resolve(root, 'AGENTS.md')
  const claudePath = resolve(root, 'CLAUDE.md')
  // The content lives in exactly one place: CLAUDE.md is only an entry point, avoiding two drifting copies
  const claudeDoc = '@AGENTS.md\n'

  if (options.check === true) {
    const problems: string[] = []
    if (!existsSync(agentsPath)) {
      problems.push('AGENTS.md does not exist — run `vobs agent-doc --write` to generate it')
    } else {
      const existing = readFileSync(agentsPath, 'utf8')
      const block = extractBlock(existing)
      if (block === null) {
        problems.push('No vobs marker block found in AGENTS.md — run `vobs agent-doc --write` to add one')
      } else if (block !== extractBlock(generated)) {
        problems.push('The vobs contract block in AGENTS.md is out of sync with the current framework version — run `vobs agent-doc --write` to sync it')
      }
    }
    if (!existsSync(claudePath)) {
      problems.push('CLAUDE.md does not exist — run `vobs agent-doc --write` to generate it (its content is just one line: `@AGENTS.md`)')
    } else if (!readFileSync(claudePath, 'utf8').includes('@AGENTS.md')) {
      problems.push('CLAUDE.md does not point to @AGENTS.md')
    }

    if (problems.length > 0) {
      console.error('[agent-doc] Contract is out of sync with the framework version:')
      for (const problem of problems) console.error(`  - ${problem}`)
      process.exitCode = 1
      return
    }
    console.log('[agent-doc] Contract matches the current framework version ✓')
    return
  }

  if (options.llms !== undefined) {
    const llmsDir = resolve(root, options.llms)
    mkdirSync(llmsDir, { recursive: true })
    const context = `${readContract()}\n`
    const diagnostics = buildDiagnosticsDoc()
    writeFileSync(resolve(llmsDir, 'llms.txt'), `${buildLlmsIndex()}\n`, 'utf8')
    writeFileSync(resolve(llmsDir, 'vobs-context.md'), context, 'utf8')
    writeFileSync(resolve(llmsDir, 'diagnostics.md'), diagnostics, 'utf8')
    // Single-code pages for on-demand fetching: an agent querying one diagnostic code
    // does not need to pull the full table (tiered distribution)
    mkdirSync(resolve(llmsDir, 'diagnostics'), { recursive: true })
    for (const guide of DIAGNOSTIC_GUIDES) {
      writeFileSync(resolve(llmsDir, 'diagnostics', `${guide.code}.md`), `${buildSingleDiagnosticDoc(guide.code)}\n`, 'utf8')
    }
    console.log(`[agent-doc] Agent knowledge-distribution files written to ${llmsDir}`)
    console.log(`  - llms.txt (index)`)
    console.log(`  - vobs-context.md (full contract, ~${estimateTokens(context)} tokens)`)
    console.log(`  - diagnostics.md (${DIAGNOSTIC_GUIDES.length} diagnostic codes, ~${estimateTokens(diagnostics)} tokens) + diagnostics/<code>.md single-code pages`)
    console.log(`Once deployed to any public path, agents can fetch and understand the contract without installing vobs.`)
    return
  }

  if (options.write !== true) {
    process.stdout.write(generated)
    return
  }

  const existingAgents = existsSync(agentsPath) ? readFileSync(agentsPath, 'utf8') : null
  writeFileSync(agentsPath, mergeAgentsDoc(existingAgents, generated), 'utf8')
  writeFileSync(claudePath, claudeDoc, 'utf8')
  console.log(`[agent-doc] Wrote ${agentsPath}`)
  console.log(`[agent-doc] Wrote ${claudePath} (content: @AGENTS.md)`)
  if (existingAgents !== null && extractBlock(existingAgents) === null) {
    console.log('[agent-doc] Your existing AGENTS.md content was preserved; the vobs contract block was appended after it.')
  }
}
