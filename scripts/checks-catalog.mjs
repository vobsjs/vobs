/*
 * `pnpm run checks` — **repository capability index**: lists "what has already been
 * done for you".
 *
 * ## Why it exists (earned through 4 measured cases of reinventing the wheel)
 *
 * This round I fell into the same failure mode **four times**:
 *
 * | # | What I duplicated | Why not caught earlier |
 * |---|---|---|
 * | 1 | `inferStateDebugName` (already existed, more correct) | Did not search exports |
 * | 2 | `onDestroy` (capability exists, named `onDispose`) | Did not search exports |
 * | 3 | `vobs check` is a repo-wide scan (the user hand-rolled one too) | Did not search commands |
 * | 4 | **`scripts/check-imports.mjs`** — written for nothing, and I broke 3 packages by "fixing" per a wrong conclusion | Did not read the file header |
 *
 * **`vobs api` cannot catch 3 and 4** — it indexes "exported symbols", while what I
 * duplicated was **"checks/scripts the repo already has"**, a different layer. What
 * would have stopped me is **that file's header comment**.
 *
 * So this index solves: compressing "search first for whether it exists" from **two
 * operations** (remember → go find) into **one** (run one command).
 *
 * ## Data sources
 *
 * - `package.json` scripts (name + command)
 * - The **first paragraph of the header comment** of the pointed-to `scripts/*.mjs`
 *   (this repo's headers are written with real substance — they usually contain "why
 *   this needs a dedicated check" and "pitfalls hit", exactly what should be read first)
 *
 * **Automatically extracted**, so it updates as the repo evolves and does not drift.
 *
 * ## Usage
 *
 * ```
 * pnpm run checks            # print the index
 * pnpm run checks -- --write # write it as docs/checks.md (easy to read directly)
 * ```
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const ROOT = process.cwd()
const json = JSON.parse(readFileSync(path.join(ROOT, 'package.json'), 'utf8'))
const scripts = json.scripts ?? {}

/** Take the **first paragraph** of a file's header comment (title sentence + the paragraph that follows). */
function headerSummary(file) {
  let text
  try { text = readFileSync(file, 'utf8') } catch { return null }
  const match = text.match(/^\s*\/\*\*([\s\S]*?)\*\//)
  if (!match) return null
  const lines = match[1]
    .split(/\r?\n/)
    .map(line => line.replace(/^\s*\*\s?/, '').trim())
  // Skip pure decoration lines; take the first run of consecutive non-empty text
  const out = []
  let started = false
  for (const line of lines) {
    if (!started) {
      if (line === '' || line.startsWith('```')) continue
      started = true
    }
    if (line === '' && out.length > 0) break
    out.push(line)
  }
  return out.join(' ').replace(/\s+/g, ' ').trim() || null
}

/** Find every .mjs under scripts/ (including subdirectories). */
function listScriptFiles(dir, depth = 0) {
  if (depth > 3 || !existsSync(dir)) return []
  const out = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) { out.push(...listScriptFiles(full, depth + 1)); continue }
    if (entry.name.endsWith('.mjs')) out.push(full)
  }
  return out
}

const scriptFiles = listScriptFiles(path.join(ROOT, 'scripts'))

/** npm script name → the repo script it runs (only .mjs under scripts/). */
function scriptFileFor(name) {
  const command = scripts[name] ?? ''
  const match = command.match(/scripts[/\\]([\w.-]+\.mjs)/)
  if (match === null) return null
  return scriptFiles.find(file => path.basename(file) === match[1]) ?? null
}

const CHECK_PREFIX = /^(?:check|verify|test|lint|release)/
const entries = Object.keys(scripts)
  .filter(name => CHECK_PREFIX.test(name) || scriptFileFor(name) !== null)
  .sort()
  .map(name => {
    const file = scriptFileFor(name)
    return {
      command: name,
      value: scripts[name],
      file: file === null ? null : path.relative(ROOT, file).split(path.sep).join('/'),
      summary: file === null ? null : headerSummary(file)
    }
  })

/** Render the full content of `docs/checks.md`. Shared by `--write` and `--check` so the two never diverge. */
function renderCatalog(entries) {
  const lines = [
    '# Repository capability index',
    '',
    '> **This file is generated by `pnpm run checks -- --write`; do not edit by hand.**',
    '>',
    '> **Look here first** before writing a new script / check / tool —',
    '> measured so far: 4 cases of reinventing the wheel, one of which broke 3 packages',
    '> per a wrong conclusion. To search **exported symbols** use `vobs api <keyword>`;',
    '> to search **diagnostic rules** use `vobs explain`.',
    ''
  ]
  for (const item of entries) {
    lines.push(`## \`${item.command}\``)
    lines.push('')
    lines.push(item.summary ?? 'No header-comment summary for this script.')
    lines.push('')
    lines.push(`- Run: \`pnpm run ${item.command}\``)
    if (item.file !== null) lines.push(`- Implementation: \`${item.file}\``)
    lines.push('')
  }
  return lines.join('\n')
}

/*
 * `--check`: compares `docs/checks.md` against the current repo and **fails** on drift.
 *
 * ## Why it must exist
 *
 * `docs/checks.md` is a **generated artifact**, and the biggest risk of generated
 * artifacts is **silent staleness** — a new script lands, a header comment changes,
 * and the doc stays old. "A trusted-but-wrong index" is exactly the root cause of
 * this round's 5 wheel reinventions (the 5th was not realizing `check-imports`
 * already existed).
 *
 * A drifting index is worse than none: it makes people **believe they searched**.
 *
 * Approach identical to `vobs agent-doc --check`: re-render → compare with disk.
 * Since the whole file is generated, comparing the full text is simplest and leaves
 * the fewest blind spots.
 */
const TARGET = path.join(ROOT, 'docs', 'checks.md')
const rendered = renderCatalog(entries)

if (process.argv.includes('--check')) {
  if (!existsSync(TARGET)) {
    console.error('docs/checks.md does not exist — run `pnpm run checks -- --write` to generate it.')
    process.exitCode = 1
  } else {
    const onDisk = readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n')
    if (onDisk !== rendered.replace(/\r\n/g, '\n')) {
      console.error('docs/checks.md is **out of sync** with the current repo — the index has gone stale.')
      console.error('  Fix: pnpm run checks -- --write')
      // Point out the first differing line to spare a manual full diff
      const a = onDisk.split('\n')
      const b = rendered.split('\n')
      for (let i = 0; i < Math.max(a.length, b.length); i++) {
        if (a[i] !== b[i]) {
          console.error(`  First difference at line ${i + 1}:`)
          console.error(`    On disk: ${a[i] ?? '(none)'}`)
          console.error(`    Current: ${b[i] ?? '(none)'}`)
          break
        }
      }
      process.exitCode = 1
    } else {
      console.log(`vobs checks --check — docs/checks.md matches the repo (${entries.length} entries) ✓`)
    }
  }
} else if (process.argv.includes('--write')) {
  writeFileSync(TARGET, rendered, 'utf8')
  console.log(`Wrote docs/checks.md (${entries.length} entries)`)
} else {
  console.log(`Repository capability index (${entries.length} entries) — look here before you start\n`)
  for (const item of entries) {
    console.log(`  ${item.command}`)
    if (item.summary !== null) console.log(`      ${item.summary.slice(0, 110)}`)
    if (item.file !== null) console.log(`      → ${item.file}`)
  }
  console.log('\nWrite as a doc: pnpm run checks -- --write')
}
